// Build-time only. No merchant pixels are transmitted. Runtime is same-origin.
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile, readdir, lstat, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname, basename } from 'node:path';
import { MODEL } from '../web/product-cutout/limits.mjs';
const web = new URL('../web/product-cutout/', import.meta.url);
const built = new URL('../build/web/product-cutout/', import.meta.url);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const sources = ['bootstrap.js', 'bridge.mjs', 'worker.mjs', 'limits.mjs', 'assets.mjs'];
const names = [...MODEL.parts.map((_, i) => `u2net-${String(i).padStart(2, '0')}.bin`),
  'ort.wasm.min.mjs', 'ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs',
  'ONNX-RUNTIME-LICENSE.txt', 'ONNX-RUNTIME-THIRD-PARTY-NOTICES.txt', 'U2NET-LICENSE.txt', 'REMBG-LICENSE.txt',
  'sniff.mjs', 'pngbound.mjs'].sort();

export const revisionFor = records => hash(JSON.stringify(records.map(({ file, bytes, sha256 }) => [file, bytes, sha256])));

// Only this preparer's fixed, gitignored outputs. Never traverse a symlink or
// accept a caller-supplied delete target (including on Windows).
async function cleanGenerated() {
  const parent = resolve(fileURLToPath(web));
  for (const name of ['assets', 'vendor', 'assets.mjs', 'asset-manifest.json']) {
    const path = resolve(parent, name);
    assert.equal(dirname(path), parent); assert.equal(basename(path), name);
    let stat; try { stat = await lstat(path); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    assert.equal(stat.isSymbolicLink(), false, 'Generated path must not be a symlink');
    await rm(path, { recursive: stat.isDirectory(), force: false });
  }
}

export async function verifyPrepared(root = web) {
  const manifest = JSON.parse(await readFile(new URL('asset-manifest.json', root), 'utf8'));
  assert.match(manifest.revision, /^[a-f0-9]{64}$/);
  assert.equal(manifest.revision, revisionFor(manifest.files));
  assert.equal(manifest.modelSha256, MODEL.sha256);
  assert.deepEqual(manifest.files.map(file => file.file), names);
  assert.deepEqual((await readdir(new URL('assets/', root))).sort(), [manifest.revision]);
  const target = new URL(`assets/${manifest.revision}/`, root);
  assert.deepEqual((await readdir(target)).sort(), names);
  for (const record of manifest.files) {
    const bytes = await readFile(new URL(record.file, target));
    assert.equal(bytes.length, record.bytes); assert.equal(hash(bytes), record.sha256);
  }
  assert.deepEqual(manifest.sources.map(file => file.file), sources);
  for (const record of manifest.sources) assert.equal(hash(await readFile(new URL(record.file, root))), record.sha256);
  assert.equal(await readFile(new URL('assets.mjs', root), 'utf8'), `// Generated by cutout/prepare.mjs; same-origin shared static assets.\nexport const vendorPath = './assets/${manifest.revision}/';\n`);
  assert.equal((await readdir(root)).includes('vendor'), false, 'No unversioned duplicate heavy assets');
  return manifest;
}

async function verifyBuild(enabled, scope = 'all-apps') {
  assert.ok(enabled === 'true' || enabled === 'false');
  assert.ok(scope === 'all-apps' || scope === 'dashboard-only');
  let manifest = null;
  if (enabled === 'true') {
    manifest = await verifyPrepared(built);
    assert.equal(hash(await readFile(new URL('asset-manifest.json', built))), hash(await readFile(new URL('asset-manifest.json', web))));
  } else {
    const files = await readdir(built);
    for (const name of ['assets', 'vendor', 'assets.mjs', 'asset-manifest.json']) assert.equal(files.includes(name), false);
  }
  for (const app of scope === 'all-apps' ? ['pos', 'kds', 'kiosk'] : []) {
    const appWeb = new URL(`../../${app}/build/web/`, import.meta.url);
    assert.equal((await readdir(appWeb)).includes('product-cutout'), false, 'Heavy processor files belong only to Dashboard');
    assert.equal((await readdir(new URL(`../${app}/`, built))).includes('product-cutout'), false, 'Assembled device apps exclude processor assets');
  }
  const source = process.env.VERCEL_GIT_COMMIT_SHA ?? process.env.GITHUB_SHA ?? null;
  const record = { enabled: enabled === 'true', featureDefine: 'SF_PRODUCT_CUTOUT_REVIEW', scope,
    sourceCommit: /^[a-f0-9]{40}$/.test(source ?? '') ? source : null,
    revision: manifest?.revision ?? null, modelSha256: manifest?.modelSha256 ?? null,
    files: manifest?.files ?? [], sources: manifest?.sources ?? [],
    assetBytes: manifest?.files.reduce((sum, file) => sum + file.bytes, 0) ?? 0 };
  await writeFile(new URL('build-record.json', built), JSON.stringify(record, null, 2) + '\n');
  console.log(`Verified Dashboard cutout build: enabled=${enabled}; assets=${record.assetBytes} bytes; revision=${record.revision ?? 'none'}`);
}

async function prepare() {
await mkdir(new URL('.cache/', import.meta.url), { recursive: true });
const modelPath = new URL('.cache/u2net.onnx', import.meta.url);
let bytes;
try { bytes = await readFile(modelPath); } catch { /* first build */ }
if (!bytes || bytes.length !== MODEL.bytes || hash(bytes) !== MODEL.sha256) {
  const response = await fetch(MODEL.buildSource);
  if (!response.ok) throw new Error(`Model fetch failed: ${response.status}`);
  bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.length !== MODEL.bytes || hash(bytes) !== MODEL.sha256) throw new Error('Model integrity mismatch');
  await writeFile(modelPath, bytes);
}
const files = new Map();
for (let i = 0; i < MODEL.parts.length; i++) {
  const part = bytes.subarray(i * MODEL.partBytes, Math.min((i + 1) * MODEL.partBytes, MODEL.bytes));
  if (hash(part) !== MODEL.parts[i]) throw new Error('Model part integrity mismatch');
  files.set(`u2net-${String(i).padStart(2, '0')}.bin`, part);
}
for (const name of ['ort.wasm.min.mjs', 'ort-wasm-simd-threaded.wasm']) {
  files.set(name, await readFile(new URL(`node_modules/onnxruntime-web/dist/${name}`, import.meta.url)));
}
// A bounded private WASM heap: 8192 pages = 512 MiB. The pinned module imports
// memory with maximum 65536; supplying a SMALLER maximum is valid WebAssembly.
// Its allocator catches memory.grow failure. No graph/weights/output changes.
const runtime = await readFile(new URL('node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.mjs', import.meta.url));
if (hash(runtime) !== '90a557d15c02bac4504d95b67f431d8594635ed2a0a62a7f2cd83d090ff91d3e') throw new Error('Runtime patch source mismatch');
const runtimeText = runtime.toString();
if (runtimeText.split('initial:256,maximum:65536,shared:!0').length !== 2) throw new Error('Runtime heap patch mismatch');
files.set('ort-wasm-simd-threaded.mjs', Buffer.from(
  '// BIZBOT modification: WASM maximum memory reduced to 512 MiB.\n' + runtimeText.replace('initial:256,maximum:65536,shared:!0', 'initial:256,maximum:8192,shared:!0')));
for (const name of ['ONNX-RUNTIME-LICENSE.txt', 'ONNX-RUNTIME-THIRD-PARTY-NOTICES.txt', 'U2NET-LICENSE.txt', 'REMBG-LICENSE.txt']) {
  files.set(name, await readFile(new URL(`licenses/${name}`, import.meta.url)));
}
for (const name of ['sniff.mjs', 'pngbound.mjs']) {
  files.set(name, await readFile(new URL(`../../../supabase/functions/storefront-media-publish/lib/${name}`, import.meta.url)));
}
const records = [...files].map(([file, bytes]) => ({ file, bytes: bytes.length, sha256: hash(bytes) }));
// Use byte/code-point sort, independent of host locale, for manifest identity.
records.sort((a, b) => a.file < b.file ? -1 : a.file > b.file ? 1 : 0);
const revision = revisionFor(records);
await cleanGenerated();
const target = new URL(`assets/${revision}/`, web);
await mkdir(target, { recursive: true });
for (const [name, bytes] of files) await writeFile(new URL(name, target), bytes);
await writeFile(new URL('assets.mjs', web), `// Generated by cutout/prepare.mjs; same-origin shared static assets.\nexport const vendorPath = './assets/${revision}/';\n`);
const sourceRecords = await Promise.all(sources.map(async file => ({ file, sha256: hash(await readFile(new URL(file, web))) })));
await writeFile(new URL('asset-manifest.json', web), JSON.stringify({ revision, modelSha256: MODEL.sha256,
  modelBytes: MODEL.bytes, nativeHeapMaxBytes: 536870912, files: records, sources: sourceRecords }, null, 2) + '\n');
await verifyPrepared();
console.log(`Prepared Dashboard-only model (${MODEL.bytes} bytes, SHA-256 verified), pinned ONNX Runtime 1.23.2 and content-addressed assets ${revision}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--clean') await cleanGenerated();
  else if (process.argv[2] === '--verify-build') await verifyBuild(process.argv[3], process.argv[4]);
  else { assert.equal(process.argv.length, 2, 'Unknown preparation option'); await prepare(); }
}
