// Offline, deterministic generation from pinned Unicode 15.1 files. No fetch.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(root, '../..');
const pins = {
  'GraphemeBreakProperty.txt': ['auxiliary/GraphemeBreakProperty.txt', 'a7e52eee647e52dc210b8719b4d7037276f4b353810293d69377fc46374cec3f'],
  'emoji-data.txt': ['emoji/emoji-data.txt', 'd7aef489c8fe4c14f09ea5695200277c6b93ac82ac60845cdd2161b0d6835cc1'],
  'DerivedCoreProperties.txt': ['DerivedCoreProperties.txt', 'f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b'],
  'GraphemeBreakTest.txt': ['auxiliary/GraphemeBreakTest.txt', 'ed9c5e92fd0911ccbeeb63c97cb19c519ea272ff1112ce843abd991582dd848f'],
  'LICENSE.txt': [null, 'e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96'],
};
const sources = {};
for (const [name, [url, sha256]] of Object.entries(pins)) {
  const bytes = readFileSync(path.join(root, 'vendor', name));
  if (createHash('sha256').update(bytes).digest('hex') !== sha256) throw Error(`Pinned Unicode source drift: ${name}`);
  sources[name] = bytes.toString('utf8');
}
const ranges = {};
function add(name, start, end) { (ranges[name] ??= []).push([start, end]); }
for (const [file, kind] of [['GraphemeBreakProperty.txt','gcb'],['emoji-data.txt','ep'],['DerivedCoreProperties.txt','incb']]) {
  for (const raw of sources[file].split('\n')) {
    const fields = raw.split('#')[0].trim().split(';').map(s => s.trim());
    if (!/^[0-9A-F]+(?:\.\.[0-9A-F]+)?$/.test(fields[0])) continue;
    let name = fields[1];
    if (kind === 'ep' && name !== 'Extended_Pictographic') continue;
    if (kind === 'incb') { if (name !== 'InCB') continue; name = `InCB_${fields[2]}`; }
    if (name === 'LV' || name === 'LVT') continue; // Algorithmic Hangul; GB6..8.
    const pair = fields[0].split('..').map(s => parseInt(s,16));
    add(name, pair[0], pair[1] ?? pair[0]);
  }
}
for (const key of Object.keys(ranges)) {
  const merged=[];
  for (const [a,b] of ranges[key].sort((x,y)=>x[0]-y[0])) {
    if (merged.length && a <= merged.at(-1)[1]+1) merged.at(-1)[1]=Math.max(b,merged.at(-1)[1]);
    else merged.push([a,b]);
  }
  ranges[key]=merged.flat();
}
const vectors=[];
for (const raw of sources['GraphemeBreakTest.txt'].split('\n')) {
  const tokens=raw.split('#')[0].trim().split(/\s+/);
  if(tokens[0]!=='÷') continue;
  const cps=[], boundaries=[];
  for(const token of tokens) { if(token==='÷') boundaries.push(cps.length); else if(token!=='×') cps.push(parseInt(token,16)); }
  vectors.push({codepoints:cps,boundaries});
}
const banner='// GENERATED by tools/storefront_content_unicode/generate.mjs. Unicode 15.1 / UAX29r43.\n// Unicode data copyright Unicode, Inc.; see tools/storefront_content_unicode/vendor/LICENSE.txt.\n';
const outputs = {
  'storefront/src/content/grapheme-data.ts': banner+`export const UNICODE_VERSION = '15.1.0' as const;\nexport const GRAPHEME_RANGES: Readonly<Record<string, readonly number[]>> = ${JSON.stringify(ranges)};\n`,
  'tools/storefront_content_unicode/vectors.json': JSON.stringify({unicode:'15.1.0',uax29:43,vectors},null,2)+'\n',
  'tools/storefront_content_unicode/provenance.json': JSON.stringify({unicode:'15.1.0',uax29:43,rule:'default extended grapheme clusters; no tailoring or normalization',files:Object.entries(pins).map(([name,[url,sha256]])=>({name,url:url?`https://www.unicode.org/Public/15.1.0/ucd/${url}`:'https://www.unicode.org/license.txt',sha256,bytes:Buffer.byteLength(sources[name])}))},null,2)+'\n',
};
// Cross-language implementations are separate source templates, with the exact
// same generated ranges and official test vectors; no platform ICU dependency.
const dartTemplate=readFileSync(path.join(root,'templates/unicode.dart.txt'),'utf8');
outputs['tools/storefront_content_unicode/generated/storefront_content_unicode.dart']=banner+dartTemplate.replace('/*RANGES*/',Object.entries(ranges).map(([k,v])=>`  '${k}': <int>[${v.join(',')}],`).join('\n'));
const sqlTemplate=readFileSync(path.join(root,'templates/unicode.sql.txt'),'utf8');
outputs['tools/storefront_content_unicode/generated/unicode-v15_1.sql']='-- GENERATED from pinned Unicode15.1/UAX29r43; see vendor/LICENSE.txt and provenance.json.\n'+sqlTemplate.replace('/*RANGES*/',Object.entries(ranges).map(([k,v])=>`WHEN '${k}' THEN v_ranges := ARRAY[${v.join(',')}]::integer[];`).join('\n'));
for(const [relative,text] of Object.entries(outputs)) {
  const filename=path.join(repo,relative);
  if(process.argv.includes('--check')) { if(readFileSync(filename,'utf8')!==text) throw Error(`Generated output drift: ${relative}`); }
  else { mkdirSync(path.dirname(filename),{recursive:true}); writeFileSync(filename,text); }
}
console.log(JSON.stringify({status:process.argv.includes('--check')?'GENERATED_PARITY_OK':'GENERATED',unicode:'15.1.0',vectors:vectors.length,outputs:Object.keys(outputs)}));
